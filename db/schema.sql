-- Таблица пользователей системы (сотрудники отдела ИБ)
CREATE TABLE Users (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Login NVARCHAR(100) NOT NULL UNIQUE,
    Password NVARCHAR(255) NOT NULL,          -- пароль хранится в хэшированном виде (SHA1)
    Role NVARCHAR(20) NOT NULL DEFAULT 'User', -- Admin / User
    FIO NVARCHAR(200) NOT NULL,
    Department NVARCHAR(100) NULL,
    Photo NVARCHAR(255) NULL                   -- путь к фотографии (необязательно)
);

-- Таблица категорий угроз информационной безопасности
CREATE TABLE ThreatCategories (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(200) NOT NULL
);

-- Таблица инцидентов информационной безопасности
CREATE TABLE SecurityIncidents (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ThreatCategoryID INT NOT NULL,
    UserID INT NOT NULL,
    Date DATETIME NOT NULL DEFAULT GETDATE(),
    Name NVARCHAR(300) NOT NULL,
    Severity INT NOT NULL CHECK (Severity BETWEEN 1 AND 5), -- критичность: 1 - низкая, 5 - критическая
    Description NVARCHAR(MAX) NULL,
    IPAddress NVARCHAR(50) NULL,
    Status NVARCHAR(50) NOT NULL DEFAULT N'Открыт', -- Открыт / В работе / Закрыт
    FOREIGN KEY (ThreatCategoryID) REFERENCES ThreatCategories(ID) ON DELETE CASCADE,
    FOREIGN KEY (UserID) REFERENCES Users(ID) ON DELETE CASCADE
);
GO

